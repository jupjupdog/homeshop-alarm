ALL_CATEGORY_NAMES = [c for c, _ in CATEGORIES] + ["기타"]

_RULES = [(i, cat, re.compile("|".join(f"(?:{k})" for k in keywords))) for i, (cat, keywords) in enumerate(CATEGORIES)]
_TAGS = re.compile(r"\[[^\]]*\]|【[^】]*】|\([^)]*\)|（[^）]*）")
_ADDON = re.compile(r"\+(?!\s*\d)")      # "+텀블러" 는 덤, "12+2박스" 는 수량


def _best(text: str) -> str | None:
    best: tuple[int, int, int, str] | None = None     # (끝 위치, 길이, -우선순위, 카테고리)
    for priority, category, rule in _RULES:
        for m in rule.finditer(text):
            key = (m.end(), m.end() - m.start(), -priority, category)
            if best is None or key > best:
                best = key
    return best[3] if best else None


def categorize(name: str) -> str:
    plain = " ".join(_TAGS.sub(" ", name).split())
    main = _ADDON.split(plain, maxsplit=1)[0].strip()
    return _best(main) or _best(plain) or _best(name) or "기타"
