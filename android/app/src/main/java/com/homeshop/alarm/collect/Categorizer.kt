    const val OTHER = "기타"
    val ALL: List<String> = CATEGORIES.map { it.first } + OTHER

    private val RULES = CATEGORIES.map { (cat, keywords) -> cat to Regex(keywords.joinToString("|") { "(?:$it)" }) }
    private val TAGS = Regex("""\[[^\]]*]|【[^】]*】|\([^)]*\)|（[^）]*）""")
    private val ADDON = Regex("""\+(?!\s*\d)""")      // "+텀블러" 는 덤, "12+2박스" 는 수량

    fun categorize(name: String): String {
        val plain = TAGS.replace(name, " ").squash()
        val main = plain.split(ADDON, limit = 2)[0].trim()
        return best(main) ?: best(plain) ?: best(name) ?: OTHER
    }

    private data class Hit(val end: Int, val length: Int, val priority: Int, val category: String)

    private fun best(text: String): String? {
        var best: Hit? = null
        RULES.forEachIndexed { priority, (category, rule) ->
            for (m in rule.findAll(text)) {
                val hit = Hit(m.range.last + 1, m.value.length, priority, category)
                val b = best
                if (b == null || hit.end > b.end || (hit.end == b.end &&
                        (hit.length > b.length || (hit.length == b.length && hit.priority < b.priority)))) {
                    best = hit
                }
            }
        }
        return best?.category
    }
